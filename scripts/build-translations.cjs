const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const pairs = JSON.parse(fs.readFileSync(path.join(root, 'content/translations.json'), 'utf8'));
const arabic = JSON.parse(fs.readFileSync(path.join(root, 'content/ar/backend-after-ai.json'), 'utf8'));
const english = JSON.parse(fs.readFileSync(path.join(root, 'content/en/backend-after-ai.json'), 'utf8'));
for (const ar of arabic.lessons) {
  const en = english.lessons.find(lesson => lesson.id === ar.id);
  if (!en) throw new Error(`Missing English lesson: ${ar.id}`);
  for (const field of ['title','category','summary','explanation','scenario','review','exercise','answer','takeaway']) {
    if (!en[field]) throw new Error(`Missing ${ar.id}.${field}`);
    pairs.push([en[field], ar[field]]);
  }
  pairs.push([`Reviewed: ${en.takeaway}`, `راجعت المحور: ${ar.takeaway}`]);
  pairs.push([`Direct link: ${en.title}`, `رابط مباشر: ${ar.title}`]);
}
for (const file of ['project-translations.json','article-translations.json']) {
  const target = path.join(root,'content',file);
  if (fs.existsSync(target)) pairs.push(...JSON.parse(fs.readFileSync(target,'utf8')));
}
const projects = JSON.parse(fs.readFileSync(path.join(root,'content/ar/projects.json'),'utf8'));
const home = fs.readFileSync(path.join(root,'index.html'),'utf8');
for (const match of home.matchAll(/<article[^>]*data-project-id="([^"]+)"[^>]*>([\s\S]*?)<\/article>/g)) {
  const key = match[0].includes('class="featured-project') ? 'featured' : match[1];
  const ar = projects[key];
  if (!ar) throw new Error(`Missing project translation: ${key}`);
  for (const field of ['desc','problem','role','solution','features','impact']) {
    const original = match[0].match(new RegExp(`data-${field}="([^"]*)"`))?.[1];
    if (!original) continue;
    const left = original.split('|'), right = ar[field].split('|');
    if (left.length !== right.length) throw new Error(`Mismatched project list: ${key}.${field}`);
    left.forEach((text,i) => pairs.push([text,right[i]]));
  }
  const summary = match[0].match(/class="project-card-summary">([\s\S]*?)<\/p>/)?.[1].replace(/\s+/g,' ').trim();
  if (summary) pairs.push([summary,ar.summary]);
}
for (const pair of pairs) if (!Array.isArray(pair) || pair.length !== 2 || pair.some(value => typeof value !== 'string')) throw new Error('Invalid translation pair');
fs.writeFileSync(path.join(root,'js/translations.js'), '// Generated by scripts/build-translations.cjs. Edit content translation files.\nwindow.SITE_TRANSLATIONS = ' + JSON.stringify(pairs, null, 2) + ';\n');
console.log(`Built ${pairs.length} translation pairs.`);
